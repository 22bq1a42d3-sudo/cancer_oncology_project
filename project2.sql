CREATE OR REPLACE TABLE CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_DATE
(
    DATE_SK NUMBER PRIMARY KEY,
    FULL_DATE DATE,
    DAY NUMBER,
    MONTH NUMBER,
    MONTH_NAME VARCHAR,
    QUARTER NUMBER,
    YEAR NUMBER,
    DAY_OF_WEEK NUMBER,
    DAY_NAME VARCHAR
);

INSERT INTO CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_DATE
(
    DATE_SK,
    FULL_DATE,
    DAY,
    MONTH,
    MONTH_NAME,
    QUARTER,
    YEAR,
    DAY_OF_WEEK,
    DAY_NAME
)
SELECT
    TO_NUMBER(TO_CHAR(DATE_VALUE, 'YYYYMMDD')) AS DATE_SK,
    DATE_VALUE,
    DAY(DATE_VALUE),
    MONTH(DATE_VALUE),
    MONTHNAME(DATE_VALUE),
    QUARTER(DATE_VALUE),
    YEAR(DATE_VALUE),
    DAYOFWEEK(DATE_VALUE),
    DAYNAME(DATE_VALUE)
FROM
(
    SELECT DATEADD(
        DAY,
        SEQ4(),
        (SELECT MIN(SERVICE_DATE)
         FROM CANCER_ONCOLOGY_DB.ONCOLOGY_RAW.RAW_ENCOUNTERS)
    )::DATE AS DATE_VALUE
    FROM TABLE(GENERATOR(ROWCOUNT => 1000))
)
WHERE DATE_VALUE <=
(
    SELECT MAX(SERVICE_DATE)
    FROM CANCER_ONCOLOGY_DB.ONCOLOGY_RAW.RAW_ENCOUNTERS
);

SELECT *
FROM CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_DATE
ORDER BY FULL_DATE;

