CREATE OR REPLACE VIEW CANCER_ONCOLOGY_DB.ONCOLOGY_SEMANTIC.VW_PATIENT_ENCOUNTERS AS
SELECT
    F.ENCOUNTER_ID,
    F.ENCOUNTER_LINE_ID,

    F.PATIENT_ID,
    P.FIRST_NAME,
    P.LAST_NAME,
    P.GENDER,
    P.DOB,
    P.CITY,
    P.STATE,
    P.COUNTRY,
    P.SEGMENT,
    P.PAYER_ID,

    F.PROVIDER_ID,
    PR.PROVIDER_NAME,
    PR.PROVIDER_TYPE,
    PR.REGION,

    F.CANCER_CODE,
    C.CANCER_NAME,
    C.CANCER_GROUP,
    C.ICD10_CODE,
    C.SPECIALTY,

    F.DISEASE_STAGE,
    F.TREATMENT_TYPE,
    F.REGIMEN_CODE,
    F.BILLED_AMOUNT,
    F.PAYMENT_MODE,
    F.ENCOUNTER_STATUS

FROM CANCER_ONCOLOGY_DB.ONCOLOGY_DW.FACT_ENCOUNTER F

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_PATIENT P
    ON F.PATIENT_SK = P.PATIENT_SK

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_PROVIDER PR
    ON F.PROVIDER_SK = PR.PROVIDER_SK

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_CANCER C
    ON F.CANCER_SK = C.CANCER_SK;

CREATE OR REPLACE VIEW CANCER_ONCOLOGY_DB.ONCOLOGY_SEMANTIC.VW_PROVIDER_PERFORMANCE AS
SELECT
    F.PROVIDER_ID,
    PR.PROVIDER_NAME,
    PR.PROVIDER_TYPE,
    PR.REGION,

    COUNT(DISTINCT F.ENCOUNTER_ID) AS TOTAL_ENCOUNTERS,
    COUNT(DISTINCT F.PATIENT_ID) AS UNIQUE_PATIENTS,
    SUM(F.BILLED_AMOUNT) AS TOTAL_BILLED_AMOUNT,
    AVG(F.BILLED_AMOUNT) AS AVG_BILLED_AMOUNT

FROM CANCER_ONCOLOGY_DB.ONCOLOGY_DW.FACT_ENCOUNTER F

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_PROVIDER PR
    ON F.PROVIDER_SK = PR.PROVIDER_SK

GROUP BY
    F.PROVIDER_ID,
    PR.PROVIDER_NAME,
    PR.PROVIDER_TYPE,
    PR.REGION;

CREATE OR REPLACE VIEW CANCER_ONCOLOGY_DB.ONCOLOGY_SEMANTIC.VW_CANCER_ANALYSIS AS
SELECT
    F.CANCER_CODE,
    C.CANCER_NAME,
    C.CANCER_GROUP,
    C.ICD10_CODE,
    C.SPECIALTY,

    COUNT(DISTINCT F.ENCOUNTER_ID) AS TOTAL_ENCOUNTERS,
    COUNT(DISTINCT F.PATIENT_ID) AS UNIQUE_PATIENTS,
    SUM(F.BILLED_AMOUNT) AS TOTAL_BILLED_AMOUNT,
    AVG(F.BILLED_AMOUNT) AS AVG_BILLED_AMOUNT

FROM CANCER_ONCOLOGY_DB.ONCOLOGY_DW.FACT_ENCOUNTER F

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_CANCER C
    ON F.CANCER_SK = C.CANCER_SK

GROUP BY
    F.CANCER_CODE,
    C.CANCER_NAME,
    C.CANCER_GROUP,
    C.ICD10_CODE,
    C.SPECIALTY;

CREATE OR REPLACE VIEW CANCER_ONCOLOGY_DB.ONCOLOGY_SEMANTIC.VW_EXECUTIVE_SUMMARY AS
