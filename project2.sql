    ON E.PROVIDER_ID = PR.PROVIDER_ID

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_PATIENT P
    ON E.PATIENT_ID = P.PATIENT_ID
    AND P.IS_CURRENT = TRUE

LEFT JOIN CANCER_ONCOLOGY_DB.ONCOLOGY_DW.DIM_CANCER C
    ON E.CANCER_CODE = C.CANCER_CODE
    AND C.IS_CURRENT = TRUE;

